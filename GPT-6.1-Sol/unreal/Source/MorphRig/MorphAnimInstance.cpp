// Evaluates the actual imported, compressed sequences. No procedural body
// animation is generated by the runtime. Ground corrections and face sliders
// are applied after the authored animation layers.
struct FMorphAnimProxy : FAnimInstanceProxy
{
    FMorphPoseInput Input;
    TArray<FTransform> LastPose, LastAuthoredPose, Snapshot;
    int32 LastSerial = -1;
    int32 LastResetSerial = -1;
    float EvaluationDelta = 0, GroundPelvisOffset = 0;
    float EffectiveFootWeights[2] = {0, 0};
    float EffectiveStanceWeights[2] = {0, 0};
    float TraceWeights[2] = {0, 0};
    struct FToePoint {int32 Side=0;FVector Reference;TArray<int32> Bones;TArray<FVector> Local;TArray<double> Weights;};
    TArray<FToePoint> ToeSurface;
    bool bLoadedToeSurface=false;
    FVector ContactWorld[2], PreviousAuthoredWorldFoot[2], PreviousMeshLocation;
    bool bContactActive[2]={false,false}, bHavePreviousFeet=false, bPreviousContactTransition=false;
    explicit FMorphAnimProxy(UAnimInstance* Instance) : FAnimInstanceProxy(Instance) {}

    virtual void PreUpdate(UAnimInstance* Instance, float Delta) override
    {
        FAnimInstanceProxy::PreUpdate(Instance, Delta);
        Input = CastChecked<UMorphAnimInstance>(Instance)->Input;
        if(LastResetSerial!=Input.ResetSerial)
        {LastResetSerial=Input.ResetSerial;Snapshot.Empty();LastAuthoredPose.Empty();LastPose.Empty();bContactActive[0]=bContactActive[1]=false;bHavePreviousFeet=bPreviousContactTransition=false;GroundPelvisOffset=0;}
        EvaluationDelta = Delta;
        USkeletalMeshComponent* Mesh = Instance->GetSkelMeshComponent();
        if (!Mesh || !Mesh->GetWorld()) return;
        if(Input.bTravelGait && Input.BaseA && Input.GaitReferenceSpeed>1)
        {
            const double Travel=FVector::DistXY(Mesh->GetOwner()->GetActorLocation(),Input.GaitActorLocation);
            const double Phase=Travel/Input.GaitReferenceSpeed/Input.BaseA->GetPlayLength();
            Input.BaseTimeA=FMath::Fmod(Input.BaseTimeA+Phase*Input.BaseA->GetPlayLength(),Input.BaseA->GetPlayLength());
            if(Input.BaseB)Input.BaseTimeB=FMath::Fmod(Input.BaseTimeB+Phase*Input.BaseB->GetPlayLength(),Input.BaseB->GetPlayLength());
        }
        if (!Input.bGroundIK || Input.bFrozen || !GetRequiredBones().IsValid())
        {if(!Input.bFrozen){bContactActive[0]=bContactActive[1]=false;bHavePreviousFeet=bPreviousContactTransition=false;}return;}
        // ACharacter schedules this mesh update after CharacterMovement.
        // Sample the same lower-body pose and transition used by Evaluate,
        // then query its current X/Y on the game thread. Previous corrected
        // sockets can lie on the other side of a stair riser for one frame.
        FPoseContext Feet(this);
        SampleLowerBody(Feet);
        ApplySnapshot(Feet);
        const FCompactPoseBoneIndex Root = Find(Feet.Pose, TEXT("root"));
        if (Root.GetInt() >= 0) Feet.Pose[Root].SetTranslation(FVector::ZeroVector);
        TArray<FTransform> Component; ComponentPose(Feet.Pose, Component);
        FPoseContext Reference(this); Reference.ResetToRefPose();
        TArray<FTransform> ReferenceComponent; ComponentPose(Reference.Pose, ReferenceComponent);
        LoadToeSurface(Mesh);
        FCollisionQueryParams Query; Query.AddIgnoredActor(Mesh->GetOwner());
        const FTransform MeshTransform = Mesh->GetComponentTransform();
        const bool bCanSeedContact=bHavePreviousFeet&&FVector::DistSquaredXY(MeshTransform.GetLocation(),PreviousMeshLocation)<10000;
        if(bHavePreviousFeet&&!bCanSeedContact){bContactActive[0]=bContactActive[1]=false;bPreviousContactTransition=false;}
        const ACharacter* Character=Cast<ACharacter>(Mesh->GetOwner());
        const double WalkableFloorZ=Character?Character->GetCharacterMovement()->GetWalkableFloorZ():.70710678;
        for (int32 Side = 0; Side < 2; ++Side)
        {
            const FCompactPoseBoneIndex Foot = Find(Feet.Pose, Side == 0 ? TEXT("foot.L") : TEXT("foot.R"));
            if (Foot.GetInt() < 0) continue;
            FVector WorldFoot = MeshTransform.TransformPosition(Component[Foot.GetInt()].GetLocation());
            const float ContactStance=1.f-FMath::SmoothStep(10.5f,15.f,float(Component[Foot.GetInt()].GetLocation().Z));
            bool bAuthoredSupport=true;
            if(Input.bTravelGait && !Input.Body && Input.BaseA)
            {
                const FString Name=Input.BaseA->GetName();
                const float Support=Name.StartsWith(TEXT("sprint_"))?.32f:Name.StartsWith(TEXT("run_"))?.37f:.62f;
                const float Phase=FMath::Fmod(Input.BaseTimeA/Input.BaseA->GetPlayLength()+(Side==0?0.f:.5f),1.f);
                bAuthoredSupport=Phase<=Support;
            }
            if(Input.bContactTransition)
            {
                if(!bAuthoredSupport||ContactStance<.999f)bContactActive[Side]=false;
                if(bAuthoredSupport && ContactStance>=.999f&&!bContactActive[Side])
                {ContactWorld[Side]=!bPreviousContactTransition&&bCanSeedContact?PreviousAuthoredWorldFoot[Side]:WorldFoot;bContactActive[Side]=true;}
                if(bContactActive[Side])
                {
                    WorldFoot.X=FMath::Lerp(WorldFoot.X,ContactWorld[Side].X,double(ContactStance));
                    WorldFoot.Y=FMath::Lerp(WorldFoot.Y,ContactWorld[Side].Y,double(ContactStance));
                    if(ContactStance<.001f)bContactActive[Side]=false;
                }
            }
            else bContactActive[Side]=false;
            PreviousAuthoredWorldFoot[Side]=WorldFoot;
            FHitResult Hit;
            const bool Found = Mesh->GetWorld()->LineTraceSingleByChannel(Hit, WorldFoot + FVector(0, 0, 35), WorldFoot - FVector(0, 0, 65), ECC_Visibility, Query);
            TraceWeights[Side] = Found ? 1.f : FMath::FInterpTo(TraceWeights[Side], 0.f, Delta, 16.f);
            Input.FootWeight[Side] = TraceWeights[Side];
            if (Found)
            {
                // A vertical ray at a ramp lip can hit its beveled end face.
                // Its downward/near-horizontal normal is collision evidence,
                // not a sole orientation. Keep authored rotation there.
                const FVector WalkableNormal=Hit.ImpactNormal.Z>=WalkableFloorZ?Hit.ImpactNormal:FVector::UpVector;
                FVector Normal = MeshTransform.InverseTransformVectorNoScale(WalkableNormal).GetSafeNormal();
                const FQuat AuthoredDelta = Component[Foot.GetInt()].GetRotation() * ReferenceComponent[Foot.GetInt()].GetRotation().Inverse();
                const float Stance = 1.f-FMath::SmoothStep(10.5f,15.f,float(Component[Foot.GetInt()].GetLocation().Z));
                const float RotationWeight = Stance*TraceWeights[Side];
                double RequiredWorldZ = -DBL_MAX;
                // The measured boot spans -4.45..18.6 cm, including its
                // independently skinned toe trim. Width is +/-5.15 cm.
                // Query the intended rotated sole, including its vertical
                // offsets, rather than adding 10 cm to the highest tread.
                {
                    const FQuat GroundRotation = FQuat::Slerp(FQuat::Identity,FQuat::FindBetweenNormals(FVector::UpVector,Normal),RotationWeight);
                    const FQuat Intended = GroundRotation * AuthoredDelta;
                    const FVector CenterOffset = MeshTransform.TransformVectorNoScale(Intended.RotateVector(FVector(0, 0, -10)));
                    RequiredWorldZ = Hit.ImpactPoint.Z - CenterOffset.Z + .10;
                    const FVector WorldNormal = MeshTransform.TransformVectorNoScale(Normal);
                    const auto PlaneHeight = [&](const FVector& Offset)
                    {return Hit.ImpactPoint.Z-(WorldNormal.X*Offset.X+WorldNormal.Y*Offset.Y)/WorldNormal.Z;};
                    bool bSurfaceEdge = false;
                    for (double X : {-4.45, 7.2, 18.6}) for (double Y : {-5.15, 0., 5.15})
                    {
                        const FVector Offset = MeshTransform.TransformVectorNoScale(Intended.RotateVector(FVector(X, Y, -10)));
                        const FVector Probe = WorldFoot + Offset;
                        FHitResult Surface;
                        if (!Mesh->GetWorld()->LineTraceSingleByChannel(Surface, Probe + FVector(0, 0, 55), Probe - FVector(0, 0, 85), ECC_Visibility, Query)) continue;
                        const double Candidate = Surface.ImpactPoint.Z - Offset.Z + .10;
                        RequiredWorldZ = FMath::Max(RequiredWorldZ,Candidate);
                        bSurfaceEdge |= FMath::Abs(Surface.ImpactPoint.Z-PlaneHeight(Offset))>.02;
                    }
                    // Toe bones retain their authored rotation independently
                    // of the ankle. Skin their unique delivered vertices.
                    // On a continuous plane their support heights are exact
                    // analytically; at an edge query every toe point instead
                    // of collapsing points on opposite sides of a riser.
                    TArray<FVector> ToeOffsets;
                    FVector Extremes[4];bool bHaveExtremes=false;
                    for(const FToePoint& Point:ToeSurface)
                    {
                        if(Point.Side!=Side)continue;FVector P=FVector::ZeroVector;bool Valid=true;
                        for(int32 I=0;I<Point.Bones.Num();++I)
                        {
                            const FCompactPoseBoneIndex Bone=GetRequiredBones().MakeCompactPoseIndex(FMeshPoseBoneIndex(Point.Bones[I]));
                            if(Bone.GetInt()<0){Valid=false;break;}
                            P+=Component[Bone.GetInt()].TransformPosition(Point.Local[I])*Point.Weights[I];
                        }
                        if(!Valid)continue;
                        const FVector Offset=MeshTransform.TransformVectorNoScale(GroundRotation.RotateVector(P-Component[Foot.GetInt()].GetLocation()));
                        ToeOffsets.Add(Offset);
                        if(!bHaveExtremes){for(FVector& E:Extremes)E=Offset;bHaveExtremes=true;}
                        if(Offset.X<Extremes[0].X)Extremes[0]=Offset;
                        if(Offset.X>Extremes[1].X)Extremes[1]=Offset;
                        if(Offset.Y<Extremes[2].Y)Extremes[2]=Offset;
                        if(Offset.Y>Extremes[3].Y)Extremes[3]=Offset;
                    }
                    if(bHaveExtremes)for(const FVector& Offset:Extremes)
                    {
                        const FVector Probe=WorldFoot+Offset;FHitResult Surface;
                        if(!Mesh->GetWorld()->LineTraceSingleByChannel(Surface,Probe+FVector(0,0,55),Probe-FVector(0,0,85),ECC_Visibility,Query))continue;
                        RequiredWorldZ=FMath::Max(RequiredWorldZ,Surface.ImpactPoint.Z-Offset.Z+.10);
                        bSurfaceEdge|=FMath::Abs(Surface.ImpactPoint.Z-PlaneHeight(Offset))>.02;
                    }
                    for(const FVector& Offset:ToeOffsets)
                    {
                        double SurfaceZ=PlaneHeight(Offset);
                        if(bSurfaceEdge)
                        {
                            const FVector Probe=WorldFoot+Offset;FHitResult Surface;
                            if(!Mesh->GetWorld()->LineTraceSingleByChannel(Surface,Probe+FVector(0,0,55),Probe-FVector(0,0,85),ECC_Visibility,Query))continue;
                            SurfaceZ=Surface.ImpactPoint.Z;
                        }
                        RequiredWorldZ=FMath::Max(RequiredWorldZ,SurfaceZ-Offset.Z+.10);
                    }
                    // Skin vertices blending shin and ankle can shift a few
                    // millimeters when the knee is solved. Retain an extra
                    // 2.5 mm at discontinuities; continuous floors keep 1 mm.
                    if(bSurfaceEdge)RequiredWorldZ+=.25;
                    // The normal beneath the ankle stays authoritative for
                    // rotation. A higher adjacent tread changes height only;
                    // changing normal after height calculation would apply
                    // a different rotation at ramp/landing boundaries.
                }
                Input.FootNormal[Side] = Normal;
                Input.FootTarget[Side] = MeshTransform.InverseTransformPosition(FVector(WorldFoot.X, WorldFoot.Y, RequiredWorldZ));
            }
        }
        bHavePreviousFeet=true;bPreviousContactTransition=Input.bContactTransition;PreviousMeshLocation=MeshTransform.GetLocation();
    }

    void LoadToeSurface(USkeletalMeshComponent* Mesh)
    {
        if(bLoadedToeSurface)return;bLoadedToeSurface=true;FString Text;TSharedPtr<FJsonObject> Data;
        if(!FFileHelper::LoadFileToString(Text,*FPaths::Combine(FPaths::ProjectContentDir(),TEXT("Data/boot_surface_bindings.json")))||!FJsonSerializer::Deserialize(TJsonReaderFactory<>::Create(Text),Data))return;
        const FReferenceSkeleton& Ref=Mesh->GetSkeletalMeshAsset()->GetRefSkeleton();TArray<FTransform> Reference;Reference.SetNum(Ref.GetNum());
        for(int32 I=0;I<Ref.GetNum();++I){const int32 Parent=Ref.GetParentIndex(I);Reference[I]=Parent>=0?Ref.GetRefBonePose()[I]*Reference[Parent]:Ref.GetRefBonePose()[I];}
        TSet<FString> Unique;
        for(const auto& Value:Data->GetArrayField(TEXT("vertices")))
        {
            const auto Row=Value->AsObject();const auto& Bones=Row->GetArrayField(TEXT("bone_indices"));bool HasToe=false;
            for(const auto& Bone:Bones)if(Ref.GetBoneName(Bone->AsNumber()).ToString().StartsWith(TEXT("toe_")))HasToe=true;
            if(!HasToe)continue;FToePoint Point;Point.Side=Row->GetIntegerField(TEXT("side"));
            const auto& P=Row->GetArrayField(TEXT("position_cm"));Point.Reference=FVector(P[0]->AsNumber(),P[1]->AsNumber(),P[2]->AsNumber());const auto& Weights=Row->GetArrayField(TEXT("weights"));
            FString Key=FString::Printf(TEXT("%.5f,%.5f,%.5f"),Point.Reference.X,Point.Reference.Y,Point.Reference.Z);
            for(int32 I=0;I<Bones.Num();++I){const int32 Bone=Bones[I]->AsNumber();Point.Bones.Add(Bone);Point.Local.Add(Reference[Bone].InverseTransformPosition(Point.Reference));Point.Weights.Add(Weights[I]->AsNumber());Key+=FString::Printf(TEXT("|%d:%.5f"),Bone,Weights[I]->AsNumber());}
            if(Unique.Contains(Key))continue;Unique.Add(Key);
            ToeSurface.Add(MoveTemp(Point));
        }
    }

    void Sample(UAnimSequence* Sequence, float Time, FPoseContext& Pose)
    {
        Pose.ResetToRefPose();
        if (Sequence)
        {
            FAnimationPoseData Data(Pose);
            FAnimExtractContext Context(FMath::Clamp<double>(Time, 0, Sequence->GetPlayLength()), true);
            Sequence->GetAnimationPose(Data, Context);
        }
    }

    void SampleLowerBody(FPoseContext& Pose)
    {
        Sample(Input.Body?Input.Body:Input.BaseA,Input.Body?Input.BodyTime:Input.BaseTimeA,Pose);
        if(!Input.Body&&Input.BaseB&&Input.DirectionAlpha>.001f)
        {FPoseContext Direction(this);Sample(Input.BaseB,Input.BaseTimeB,Direction);Blend(Pose,Direction,Input.DirectionAlpha,false);}
    }

    FName BoneName(FCompactPoseBoneIndex Index) const
    {
        const FBoneContainer& Bones = GetRequiredBones();
        return Bones.GetReferenceSkeleton().GetBoneName(Bones.MakeMeshPoseIndex(Index).GetInt());
    }

    FCompactPoseBoneIndex Find(const FCompactPose& Pose, const TCHAR* Name) const
    {
        FString Alternate(Name); Alternate.ReplaceInline(TEXT("."), TEXT("_"));
        for (const FCompactPoseBoneIndex Index : Pose.ForEachBoneIndex())
            if (BoneName(Index) == FName(Name) || BoneName(Index) == FName(*Alternate)) return Index;
        return FCompactPoseBoneIndex(INDEX_NONE);
    }

    bool IsUpper(FCompactPoseBoneIndex Index) const
    {
        const FBoneContainer& Bones = GetRequiredBones();
        const FReferenceSkeleton& Ref = Bones.GetReferenceSkeleton();
        const int32 MeshIndex = Bones.MakeMeshPoseIndex(Index).GetInt();
        const int32 Spine = Ref.FindBoneIndex(TEXT("spine_01"));
        const FName Name = Ref.GetBoneName(MeshIndex);
        return MeshIndex == Spine || (Spine >= 0 && Ref.BoneIsChildOf(MeshIndex, Spine))
            || Name == TEXT("cell") || Name == TEXT("beacon") || Name == TEXT("blade");
    }

    void Blend(FPoseContext& Output, const FPoseContext& Other, float Weight, bool bUpper)
    {
        for (FCompactPoseBoneIndex Index : Output.Pose.ForEachBoneIndex())
        {
            if (!bUpper || IsUpper(Index))
            {
                FTransform Result;
                Result.Blend(Output.Pose[Index], Other.Pose[Index], Weight);
                Output.Pose[Index] = Result;
            }
        }
        if (!bUpper) Output.Curve.LerpTo(Other.Curve, Weight);
    }

    void ComponentPose(const FCompactPose& Pose, TArray<FTransform>& Component)
    {
        Component.SetNum(Pose.GetNumBones());
        for (FCompactPoseBoneIndex Index : Pose.ForEachBoneIndex())
        {
            const FCompactPoseBoneIndex Parent = GetRequiredBones().GetParentBoneIndex(Index);
            Component[Index.GetInt()] = Parent.GetInt() >= 0 ? Pose[Index] * Component[Parent.GetInt()] : Pose[Index];
        }
    }

    void ApplySnapshot(FPoseContext& Output)
    {
        if (LastSerial != Input.TransitionSerial && LastAuthoredPose.Num() == Output.Pose.GetNumBones())
        {
            // LastPose includes ground IK and remains reserved for stasis.
            Snapshot = LastAuthoredPose;
            const FCompactPoseBoneIndex Root = Find(Output.Pose, TEXT("root"));
            if (Root.GetInt() >= 0 && Input.FacingCompensation != 0)
            {
                const FQuat Counter(FVector::UpVector, FMath::DegreesToRadians(-Input.FacingCompensation));
                Snapshot[Root.GetInt()].SetRotation((Counter * Snapshot[Root.GetInt()].GetRotation()).GetNormalized());
                Snapshot[Root.GetInt()].SetTranslation(Counter.RotateVector(Snapshot[Root.GetInt()].GetTranslation()));
            }
        }
        LastSerial = Input.TransitionSerial;
        if (Snapshot.Num() == Output.Pose.GetNumBones() && Input.TransitionTime < .14f)
        {
            const float Alpha = FMath::SmoothStep(0.f, 1.f, Input.TransitionTime / .14f);
            for (FCompactPoseBoneIndex Index : Output.Pose.ForEachBoneIndex())
            {
                if(Input.bUpperSnapshot&&!IsUpper(Index))continue;
                FTransform Result; Result.Blend(Snapshot[Index.GetInt()], Output.Pose[Index], Alpha);
                Output.Pose[Index] = Result;
            }
        }
    }

    void ApplyIK(FPoseContext& Output)
    {
        EffectiveFootWeights[0] = EffectiveFootWeights[1] = 0;
        EffectiveStanceWeights[0] = EffectiveStanceWeights[1] = 0;
        if (!Input.bGroundIK) { GroundPelvisOffset = 0; return; }
        const FCompactPoseBoneIndex Pelvis = Find(Output.Pose, TEXT("pelvis"));
        TArray<FTransform> Authored; ComponentPose(Output.Pose, Authored);
        FCompactPoseBoneIndex Thigh[2], Shin[2], Foot[2];
        FVector Targets[2];
        float RequiredDrop = 0;
        for (int32 Side = 0; Side < 2; ++Side)
        {
            Thigh[Side] = Find(Output.Pose, Side == 0 ? TEXT("thigh.L") : TEXT("thigh.R"));
            Shin[Side] = Find(Output.Pose, Side == 0 ? TEXT("shin.L") : TEXT("shin.R"));
            Foot[Side] = Find(Output.Pose, Side == 0 ? TEXT("foot.L") : TEXT("foot.R"));
            if (Thigh[Side].GetInt() < 0 || Shin[Side].GetInt() < 0 || Foot[Side].GetInt() < 0) continue;
            const FVector A = Authored[Thigh[Side].GetInt()].GetLocation();
            const FVector B = Authored[Shin[Side].GetInt()].GetLocation();
            const FVector C = Authored[Foot[Side].GetInt()].GetLocation();
            // Derive stance from this frame's authored lift. Reading the
            // previous IK result makes a corrected swing foot look planted.
            const float Stance = 1.f-FMath::SmoothStep(10.5f, 15.f, float(C.Z));
            EffectiveStanceWeights[Side] = Stance*Input.FootWeight[Side];
            const bool bObstacleAboveFoot = Input.FootTarget[Side].Z > C.Z;
            const float Weight = Input.FootWeight[Side]*(bObstacleAboveFoot ? 1.f : Stance);
            EffectiveFootWeights[Side] = Weight;
            Targets[Side] = C;
            if(Input.bContactTransition){Targets[Side].X=Input.FootTarget[Side].X;Targets[Side].Y=Input.FootTarget[Side].Y;}
            Targets[Side].Z = FMath::Lerp(C.Z, Input.FootTarget[Side].Z, double(Weight));
            // A capsule climbing a stair raises both hips. Lower the pelvis
            // enough for the trailing leg's actual length and horizontal
            // reach, instead of allowing the IK solver to clamp a short leg.
            const double Reach = ((A-B).Size()+(B-C).Size())*.985;
            const double HorizontalSquared = FVector::DistSquaredXY(A, Targets[Side]);
            const double VerticalReach = FMath::Sqrt(FMath::Max(0., Reach*Reach-HorizontalSquared));
            RequiredDrop = FMath::Min(RequiredDrop, float(Targets[Side].Z+VerticalReach-A.Z));
        }
        RequiredDrop = FMath::Clamp(RequiredDrop, -32.f, 0.f);
        // Descend immediately to retain contacts at a collision step-up;
        // recover smoothly as the trailing foot reaches the higher surface.
        GroundPelvisOffset = RequiredDrop < GroundPelvisOffset ? RequiredDrop
            : FMath::FInterpTo(GroundPelvisOffset, RequiredDrop, EvaluationDelta, 12.f);
        if (Pelvis.GetInt() >= 0) Output.Pose[Pelvis].AddToTranslation(FVector(0, 0, GroundPelvisOffset));
        for (int32 Side = 0; Side < 2; ++Side)
        {
            if (Thigh[Side].GetInt() < 0 || Shin[Side].GetInt() < 0 || Foot[Side].GetInt() < 0) continue;
            if (EffectiveFootWeights[Side] < .001f && FMath::Abs(GroundPelvisOffset) < .001f) continue;
            TArray<FTransform> CS; ComponentPose(Output.Pose, CS);
            FTransform A = CS[Thigh[Side].GetInt()], B = CS[Shin[Side].GetInt()], C = CS[Foot[Side].GetInt()];
            const FVector Pole = B.GetLocation() + FVector(60, 0, 10);
            AnimationCore::SolveTwoBoneIK(A, B, C, Pole, Targets[Side], false, 1.0, 1.0);
            const FQuat GroundRotation = FQuat::FindBetweenNormals(FVector::UpVector, Input.FootNormal[Side]);
            const float Stance=1.f-FMath::SmoothStep(10.5f,15.f,float(Authored[Foot[Side].GetInt()].GetLocation().Z));
            C.SetRotation(FQuat::Slerp(C.GetRotation(), GroundRotation * C.GetRotation(), Stance*Input.FootWeight[Side]).GetNormalized());
            const FCompactPoseBoneIndex Parent = GetRequiredBones().GetParentBoneIndex(Thigh[Side]);
            Output.Pose[Thigh[Side]] = Parent.GetInt() >= 0 ? A.GetRelativeTransform(CS[Parent.GetInt()]) : A;
            Output.Pose[Shin[Side]] = B.GetRelativeTransform(A);
            Output.Pose[Foot[Side]] = C.GetRelativeTransform(B);
        }
    }

    void FaceBone(FPoseContext& Output, const TCHAR* Bone, FRotator Rotation, FVector Translation = FVector::ZeroVector)
    {
        const FCompactPoseBoneIndex Index = Find(Output.Pose, Bone);
        if (Index.GetInt() < 0) return;
        Output.Pose[Index].SetRotation((Output.Pose[Index].GetRotation() * Rotation.Quaternion()).GetNormalized());
        Output.Pose[Index].AddToTranslation(Translation);
    }

    virtual bool Evaluate(FPoseContext& Output) override
    {
        if (Input.bFrozen && LastPose.Num() == Output.Pose.GetNumBones())
        {
            Output.ResetToRefPose();
            for (FCompactPoseBoneIndex Index : Output.Pose.ForEachBoneIndex()) Output.Pose[Index] = LastPose[Index.GetInt()];
            return true;
        }
        SampleLowerBody(Output);
        if(Input.TravelTransition)
        {FPoseContext Transition(this);Sample(Input.TravelTransition,Input.TravelTransitionTime,Transition);Blend(Output,Transition,1.f,true);}
        FPoseContext AimPose(this);bool bHasAim = false;
        if (!Input.Body && Input.AimWeight > 0.001f)
        {
            bool bFirst = true; float Sum = 0;
            for (int32 I = 0; I < 4; ++I)
            {
                if (!Input.Aim[I] || Input.AimWeights[I] < 0.001f) continue;
                FPoseContext Corner(this); Sample(Input.Aim[I], 0, Corner);
                if (bFirst) { AimPose = Corner; Sum = Input.AimWeights[I]; bFirst = false; }
                else { Sum += Input.AimWeights[I]; Blend(AimPose, Corner, Input.AimWeights[I] / Sum, false); }
            }
            if (!bFirst) {Blend(Output, AimPose, Input.AimWeight, true);bHasAim=true;}
        }
        if (Input.Upper && Input.UpperWeight > 0.001f)
        {
            FPoseContext Upper(this); Sample(Input.Upper, Input.UpperTime, Upper);
            Blend(Output, Upper, Input.UpperWeight, true);
            if (bHasAim)
            {
                FPoseContext Center(this);
                // The zero-yaw/pitch sample is supplied separately as an aim
                // reference. Add its delta to the action, preserving recoil.
                Sample(Input.NeutralAim,0,Center);
                for(FCompactPoseBoneIndex Index:Output.Pose.ForEachBoneIndex())
                {
                    if(!IsUpper(Index))continue;
                    const float Weight=Input.UpperWeight*Input.AimWeight;
                    const FQuat Delta=AimPose.Pose[Index].GetRotation()*Center.Pose[Index].GetRotation().Inverse();
                    Output.Pose[Index].SetRotation((FQuat::Slerp(FQuat::Identity,Delta,Weight)*Output.Pose[Index].GetRotation()).GetNormalized());
                    Output.Pose[Index].AddToTranslation((AimPose.Pose[Index].GetTranslation()-Center.Pose[Index].GetTranslation())*Weight);
                }
            }
        }
        if (Input.Hit && Input.HitWeight > 0.001f)
        {
            FPoseContext Hit(this), Neutral(this);
            Sample(Input.Hit, Input.HitTime, Hit); Sample(Input.Neutral, 0, Neutral);
            for (FCompactPoseBoneIndex Index : Output.Pose.ForEachBoneIndex())
            {
                // Local-space delta preserves the lower-body contact pose.
                if (!IsUpper(Index)) continue;
                const FQuat Delta = Hit.Pose[Index].GetRotation() * Neutral.Pose[Index].GetRotation().Inverse();
                Output.Pose[Index].SetRotation((FQuat::Slerp(FQuat::Identity, Delta, Input.HitWeight) * Output.Pose[Index].GetRotation()).GetNormalized());
                Output.Pose[Index].AddToTranslation((Hit.Pose[Index].GetTranslation() - Neutral.Pose[Index].GetTranslation()) * Input.HitWeight);
            }
        }
        ApplySnapshot(Output);
        // The extracted root is always capsule motion; retain the ground-root
        // reference pose so the skinned character never escapes its capsule.
        const FCompactPoseBoneIndex Root = Find(Output.Pose, TEXT("root"));
        if (Root.GetInt() >= 0) Output.Pose[Root].SetTranslation(FVector::ZeroVector);
        // The authored nine-sample aim layer already contains head look.
        // Keep its fitted bone basis and the speech head performance intact.
        if(Input.bFaceOverride)
        {
            FPoseContext NeutralFace(this);NeutralFace.ResetToRefPose();
            for(FCompactPoseBoneIndex Index:Output.Pose.ForEachBoneIndex())
            {
                const FString Name=BoneName(Index).ToString();
                if(Name.StartsWith(TEXT("eye_"))||Name.StartsWith(TEXT("brow_"))||Name.StartsWith(TEXT("lid_"))||Name.StartsWith(TEXT("lip_"))||Name.StartsWith(TEXT("cheek_"))||Name==TEXT("jaw")||Name==TEXT("tongue"))Output.Pose[Index]=NeutralFace.Pose[Index];
            }
        }
        LastAuthoredPose.SetNum(Output.Pose.GetNumBones());
        for(FCompactPoseBoneIndex Index:Output.Pose.ForEachBoneIndex())LastAuthoredPose[Index.GetInt()]=Output.Pose[Index];
        ApplyIK(Output);
        if(Input.bBeaconDeployed)
        {
            const FCompactPoseBoneIndex Beacon=Find(Output.Pose,TEXT("beacon"));
            if(Beacon.GetInt()>=0)Output.Pose[Beacon].SetScale3D(FVector::ZeroVector);
        }
        LastPose.SetNum(Output.Pose.GetNumBones());
        for (FCompactPoseBoneIndex Index : Output.Pose.ForEachBoneIndex()) LastPose[Index.GetInt()] = Output.Pose[Index];
        Output.Pose.NormalizeRotations();
        return true;
    }
};

FAnimInstanceProxy* UMorphAnimInstance::CreateAnimInstanceProxy() { return new FMorphAnimProxy(this); }
void UMorphAnimInstance::DestroyAnimInstanceProxy(FAnimInstanceProxy* Proxy) { delete static_cast<FMorphAnimProxy*>(Proxy); }
void UMorphAnimInstance::NativePostEvaluateAnimation()
{
    Super::NativePostEvaluateAnimation();
    const FMorphAnimProxy& Proxy = GetProxyOnGameThread<FMorphAnimProxy>();
    EvaluatedPelvisOffset = Proxy.GroundPelvisOffset;
    EvaluatedFootWeights[0] = Proxy.EffectiveFootWeights[0];
    EvaluatedFootWeights[1] = Proxy.EffectiveFootWeights[1];
    EvaluatedStanceWeights[0] = Proxy.EffectiveStanceWeights[0];
    EvaluatedStanceWeights[1] = Proxy.EffectiveStanceWeights[1];
    EvaluatedBaseId=Proxy.Input.BaseA?Proxy.Input.BaseA->GetFName():NAME_None;
    EvaluatedGaitPhase=Proxy.Input.BaseA?Proxy.Input.BaseTimeA/Proxy.Input.BaseA->GetPlayLength():0;
}
