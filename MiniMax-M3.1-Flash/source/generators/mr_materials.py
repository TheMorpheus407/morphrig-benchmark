def tex_skin(n=1024, seed=11):
    base = np.empty((n, n, 3), np.float32)
    tone = np.array([0.78, 0.60, 0.52], np.float32)
    pores = fbm(n, seed, octaves=6, base=48)
    blotch = fbm(n, seed + 31, octaves=3, base=5)
    h = pores * 0.6 + blotch * 0.4
    base[:, :, 0] = tone[0] * (0.86 + 0.18 * blotch)
    base[:, :, 1] = tone[1] * (0.86 + 0.18 * blotch)
    base[:, :, 2] = tone[2] * (0.88 + 0.16 * blotch)
    base *= (0.94 + 0.10 * pores)[:, :, None]
    nrm = normal_from_height(h, 1.6)
    orm = np.zeros((n, n, 3), np.float32)
    orm[:, :, 0] = 1.0
    orm[:, :, 1] = np.clip(0.52 + 0.22 * pores, 0.2, 0.9)
    orm[:, :, 2] = 0.0
    return base, nrm, orm


def _lip_patch(upper=True, x0=0.0, x1=1.0, w=256, h=96):
    """A lip shape: a lens with a cupid's bow on the upper lip.

    `x0` and `x1` select the part of the mouth that this patch covers.
    The mouth is split by the uv seam of the head, so the two halves are
    painted into the two ends of the skin band.  The patch carries its own
    alpha, the skin outside the lip stays untouched.
    """
    img = np.zeros((h, w, 4), np.float32)
    xs = x0 + (x1 - x0) * (np.arange(w) / float(w - 1))
    ys = np.arange(h) / float(h - 1)
    if upper:
        # the upper lip sits above the lip line, the bow dips in the middle
        thick = 0.92 - 0.10 * np.cos(2.0 * np.pi * (xs - 0.5)) ** 2
        mask = (ys[:, None] <= thick[None, :]).astype(np.float32)
        mask *= np.clip((thick[None, :] - ys[:, None]) * 9.0 + 0.5, 0.0, 1.0)
    else:
        # the lower lip is fuller
        thick = 0.86 + 0.12 * np.sin(np.pi * xs)
        mask = (ys[:, None] >= (1.0 - thick)[None, :]).astype(np.float32)
        mask *= np.clip((ys[:, None] - (1.0 - thick)[None, :]) * 9.0 + 0.5,
                        0.0, 1.0)
    img[:, :, 0] = 0.54
    img[:, :, 1] = 0.24
    img[:, :, 2] = 0.23
    img[:, :, 3] = mask
    return img


def _brow_patch(w=256, h=72):
    """A brow: an arched stroke that tapers towards the temple."""
    img = np.zeros((h, w, 4), np.float32)
    xs = np.arange(w) / float(w - 1)
    ys = np.arange(h) / float(h - 1)
    # the stroke rises in the middle and falls towards the temple
    centre = 0.62 - 0.30 * np.sin(np.pi * np.clip(xs, 0.0, 1.0) ** 0.9)
    thick = 0.25 + 0.30 * np.sin(np.pi * np.clip(xs, 0.0, 1.0) ** 0.6)
    d = np.abs(ys[:, None] - centre[None, :])
    mask = np.clip(1.0 - d / thick[None, :], 0.0, 1.0) ** 0.55
    img[:, :, 0] = 0.115
    img[:, :, 1] = 0.098
    img[:, :, 2] = 0.092
    img[:, :, 3] = mask
    return img


def _socket_patch(size=160):
    """A soft shadow around the eye socket."""
    img = np.zeros((size, size, 4), np.float32)
    yy, xx = np.mgrid[0:size, 0:size].astype(np.float32) / float(size)
    r = np.sqrt(((xx - 0.5) * 1.6) ** 2 + ((yy - 0.5) * 2.2) ** 2) / 0.5
    mask = np.clip(1.0 - r, 0.0, 1.0) ** 1.6
    img[:, :, 0] = 0.48
    img[:, :, 1] = 0.34
    img[:, :, 2] = 0.31
    img[:, :, 3] = mask
    return img


def tex_face(n=2048, seed=21, layout=None):
    """Face atlas: skin region, sclera, teeth and painted lips / brows."""
    base = np.empty((n, n, 3), np.float32)
    tone = np.array([0.80, 0.63, 0.55], np.float32)
    pores = fbm(n, seed, octaves=6, base=56)
    blotch = fbm(n, seed + 7, octaves=3, base=6)
    h = pores * 0.5 + blotch * 0.5
    base[:, :, 0] = tone[0] * (0.88 + 0.16 * blotch)
    base[:, :, 1] = tone[1] * (0.88 + 0.16 * blotch)
    base[:, :, 2] = tone[2] * (0.90 + 0.14 * blotch)
    base *= (0.95 + 0.09 * pores)[:, :, None]

    # The uv seam of the head sits at the front centre, the two ends of
    # the skin band meet there.  The noise is cross faded over the last
    # few columns so the seam disappears.
    band = int(round(SKIN_BAND_U * n))
    fade = min(48, band // 4)
    if fade > 1:
        for i in range(fade):
            t = (i + 0.5) / float(fade)
            a = base[:, i].copy()
            b = base[:, band - fade + i].copy()
            mixed = a * (1.0 - t) + b * t
            base[:, i] = mixed
            base[:, band - fade + i] = mixed

    # a soft shadow under the jaw and a warm blush over the cheek bones.
    # The head uses the u range 0..0.48 of the atlas and the v band
    # 0.06..0.86, the face sits in the lower third of it.
    yy = (np.arange(n) / float(n))[:, None]
    xx = (np.arange(n) / float(n))[None, :]
    jaw = np.clip((0.075 - yy) / 0.075, 0.0, 1.0) ** 1.4
    base *= (1.0 - 0.22 * jaw)[:, :, None]
    cheek = (np.exp(-((xx - 0.090) ** 2) / 0.0022) +
             np.exp(-((xx - 0.390) ** 2) / 0.0022))
    blush = np.exp(-((yy - 0.226) ** 2) / 0.0016) * cheek
    base[:, :, 0] = np.clip(base[:, :, 0] + 0.070 * blush, 0.0, 1.0)
    base[:, :, 2] = np.clip(base[:, :, 2] - 0.030 * blush, 0.0, 1.0)

    # sclera
    sc = np.zeros((256, 256, 3), np.float32)
    vein = ridge(256, seed + 91, octaves=4, base=7)
    sc[:, :, 0] = 0.78 - 0.10 * vein
    sc[:, :, 1] = 0.77 - 0.10 * vein
    sc[:, :, 2] = 0.75 - 0.09 * vein
    paint_rect(base, (0.52, 0.88, 0.74, 1.00), sc, n)

    # teeth
    th = np.zeros((256, 256, 3), np.float32)
    wear = fbm(256, seed + 55, octaves=3, base=12)
    th[:, :, 0] = 0.90 - 0.06 * wear
    th[:, :, 1] = 0.88 - 0.06 * wear
    th[:, :, 2] = 0.80 - 0.05 * wear
    paint_rect(base, (0.76, 0.88, 0.98, 1.00), th, n)

    # painted features (optional, needs the head uv layout)
    if layout:
        shapes = {}
        for k, v in layout.items():
            if k.startswith("lipshape_"):
                shapes[k[len("lipshape_"):]] = v
        for key, rect in layout.items():
            if key.startswith("lipshape_"):
                continue
            if key.startswith("lip"):
                parts = key.split("_")
                upper = parts[1] == "upper"
                x0, x1 = shapes.get("%s_%s" % (parts[1], parts[2]), (0.0, 1.0))
                paint_rect(base, rect, _lip_patch(upper, x0, x1), n, blend=0.88)
            elif key.startswith("brow"):
                paint_rect(base, rect, _brow_patch(), n, blend=0.85)
            elif key.startswith("socket"):
                paint_rect(base, rect, _socket_patch(), n, blend=0.65)

    nrm = normal_from_height(h, 1.4)
    # flat regions for sclera / teeth
    orm = np.zeros((n, n, 3), np.float32)
    orm[:, :, 0] = 1.0
    orm[:, :, 1] = np.clip(0.50 + 0.20 * pores, 0.2, 0.9)
    orm[:, :, 2] = 0.0
    return base, nrm, orm


def tex_suit(n=1024, seed=31):
    """Technical undersuit: fine weave, panel seams and wear."""
    base = np.empty((n, n, 3), np.float32)
    weave = (np.sin(np.arange(n) * 1.55)[:, None] *
             np.sin(np.arange(n) * 1.55)[None, :]) * 0.5 + 0.5
    weave = weave.astype(np.float32)
    grit = fbm(n, seed, octaves=5, base=64)
    wear = fbm(n, seed + 17, octaves=3, base=7)
    tone = np.array([0.20, 0.22, 0.26], np.float32)
    shade = 0.80 + 0.22 * weave * 0.35 + 0.22 * grit + 0.18 * wear
    base[:, :, 0] = tone[0] * shade
    base[:, :, 1] = tone[1] * shade
    base[:, :, 2] = tone[2] * shade
    h = weave * 0.35 + grit * 0.65
    nrm = normal_from_height(h, 1.1)
    orm = np.zeros((n, n, 3), np.float32)
    orm[:, :, 0] = 0.90 + 0.10 * wear
    orm[:, :, 1] = np.clip(0.74 - 0.20 * grit + 0.10 * wear, 0.25, 0.95)
    orm[:, :, 2] = 0.05
    return base, nrm, orm


def tex_armor(n=1024, seed=41):
    """Hard armour: panel lines, chamfers, scratches and grime."""
    base = np.empty((n, n, 3), np.float32)
    tone = np.array([0.33, 0.35, 0.39], np.float32)
    grime = fbm(n, seed, octaves=5, base=9)
    micro = fbm(n, seed + 5, octaves=4, base=72)
    h = np.zeros((n, n), np.float32)
    # panel grid
    g = n // 4
    seam = np.zeros((n, n), np.float32)
    for k in range(0, n, g):
        seam[k, :] = 1.0
        seam[:, k] = 1.0
    seam = np.minimum(seam, 1.0)
    h -= seam * 0.5
    scratch = (ridge(n, seed + 23, octaves=3, base=24) > 0.93).astype(np.float32)
    h += scratch * 0.12
    shade = 0.82 + 0.26 * grime + 0.10 * micro - seam * 0.22
    base[:, :, 0] = tone[0] * shade
    base[:, :, 1] = tone[1] * shade
    base[:, :, 2] = tone[2] * shade
    base += (scratch * 0.10)[:, :, None]
    nrm = normal_from_height(h, 2.4)
    orm = np.zeros((n, n, 3), np.float32)
    orm[:, :, 0] = 0.88 + 0.12 * grime
    orm[:, :, 1] = np.clip(0.46 + 0.26 * grime - scratch * 0.15, 0.12, 0.9)
    orm[:, :, 2] = np.clip(0.55 + 0.35 * micro, 0.0, 1.0)
    return base, nrm, orm


def tex_metal(n=1024, seed=51):
    """Machined metal: brushed lines, bolts and anodised tint."""
    base = np.empty((n, n, 3), np.float32)
    brush = value_noise(n, 256, seed) * 0.6 + value_noise(n, 512, seed + 3) * 0.4
    tone = np.array([0.55, 0.58, 0.62], np.float32)
    grime = fbm(n, seed + 9, octaves=4, base=11)
    shade = 0.84 + 0.20 * brush + 0.16 * grime
    base[:, :, 0] = tone[0] * shade
    base[:, :, 1] = tone[1] * shade
    base[:, :, 2] = tone[2] * shade * 1.02
    h = brush * 0.5 + grime * 0.2
    nrm = normal_from_height(h, 1.0)
    orm = np.zeros((n, n, 3), np.float32)
    orm[:, :, 0] = 0.92 + 0.08 * grime
    orm[:, :, 1] = np.clip(0.30 + 0.24 * brush + 0.14 * grime, 0.10, 0.8)
    orm[:, :, 2] = np.clip(0.88 + 0.10 * grime, 0.0, 1.0)
    return base, nrm, orm


def tex_optic(n=1024, seed=61):
    """Dark technical surface used for hair, brows, lenses and cabling."""
    base = np.empty((n, n, 3), np.float32)
    strand = ridge(n, seed, octaves=5, base=40)
    strand2 = ridge(n, seed + 4, octaves=4, base=90)
    tone = np.array([0.10, 0.10, 0.12], np.float32)
    shade = 0.70 + 0.55 * strand * 0.6 + 0.25 * strand2
    base[:, :, 0] = tone[0] * shade
    base[:, :, 1] = tone[1] * shade
    base[:, :, 2] = tone[2] * shade * 1.15
    h = strand * 0.7 + strand2 * 0.3
    nrm = normal_from_height(h, 1.6)
    orm = np.zeros((n, n, 3), np.float32)
    orm[:, :, 0] = 0.85 + 0.15 * strand
    orm[:, :, 1] = np.clip(0.38 + 0.24 * strand2, 0.15, 0.85)
    orm[:, :, 2] = 0.10
    # hair striation patch
    hair = np.zeros((n, n, 3), np.float32)
    hs = ridge(n, seed + 77, octaves=4, base=120)
    hair[:, :, 0] = 0.12 * (0.5 + hs)
    hair[:, :, 1] = 0.11 * (0.5 + hs)
    hair[:, :, 2] = 0.13 * (0.5 + hs)
    paint_rect(base, (0.60, 0.02, 0.98, 0.30), hair, n, blend=0.9)

    # iris: a cool stroma with radial fibres and a dark limbal ring.  The
    # eyeball samples this rectangle radially, so the fibres of the texture
    # land as the fibres of the iris.
    m = 256
    yy, xx = np.mgrid[0:m, 0:m].astype(np.float32) / float(m)
    rr = np.sqrt((xx - 0.5) ** 2 + (yy - 0.5) ** 2) / 0.5
    ang = np.arctan2(yy - 0.5, xx - 0.5)
    fibre = 0.5 + 0.5 * np.sin(ang * 34.0 + rr * 5.0)
    fibre = fibre * 0.35 + 0.65 * (0.5 + 0.5 * np.sin(ang * 71.0))
    iris = np.zeros((m, m, 3), np.float32)
    iris[:, :, 0] = 0.30 + 0.20 * fibre
    iris[:, :, 1] = 0.44 + 0.22 * fibre
    iris[:, :, 2] = 0.52 + 0.18 * fibre
    iris *= np.clip(1.15 - rr * 0.85, 0.15, 1.2)[:, :, None]
    limbus = np.clip((rr - 0.80) / 0.16, 0.0, 1.0)[:, :, None]
    iris = iris * (1.0 - limbus) + np.array([0.05, 0.06, 0.07], np.float32) * limbus
    paint_rect(base, (0.03, 0.52, 0.25, 0.74), iris, n)

    # pupil: a flat black disc
    pupil = np.zeros((m, m, 3), np.float32)
    pupil[:, :, 0] = 0.012
    pupil[:, :, 1] = 0.012
    pupil[:, :, 2] = 0.016
    paint_rect(base, (0.32, 0.52, 0.44, 0.64), pupil, n)
    return base, nrm, orm


def tex_energy(n=512, seed=71):
    """Emissive surface: hot core with scan rings."""
    base = np.empty((n, n, 3), np.float32)
    yy, xx = np.mgrid[0:n, 0:n].astype(np.float32) / float(n)
    rings = 0.5 + 0.5 * np.sin((xx + yy) * 42.0)
    core = 0.75 + 0.25 * rings
    warm = np.array([1.0, 0.62, 0.22], np.float32)
    base[:, :, 0] = warm[0] * core
    base[:, :, 1] = warm[1] * core
    base[:, :, 2] = warm[2] * core
    h = rings
    nrm = normal_from_height(h, 0.5)
    orm = np.zeros((n, n, 3), np.float32)
    orm[:, :, 0] = 1.0
    orm[:, :, 1] = 0.25
    orm[:, :, 2] = 0.0
    return base, nrm, orm


def tex_accent(n=512, seed=81):
    """Team accent stripe: diagonal hazard hatching on a dark base."""
    base = np.empty((n, n, 3), np.float32)
    yy, xx = np.mgrid[0:n, 0:n].astype(np.float32) / float(n)
    hatch = ((xx + yy) * 14.0).astype(np.int32) % 2
    grain = fbm(n, seed, octaves=4, base=32)
    tone = np.array([1.0, 0.62, 0.18], np.float32)
    base[:, :, 0] = tone[0] * (0.85 + 0.25 * hatch) * (0.92 + 0.12 * grain)
    base[:, :, 1] = tone[1] * (0.85 + 0.25 * hatch) * (0.92 + 0.12 * grain)
    base[:, :, 2] = tone[2] * (0.85 + 0.25 * hatch) * (0.92 + 0.12 * grain)
    h = hatch.astype(np.float32) * 0.5 + grain * 0.3
    nrm = normal_from_height(h, 0.8)
    orm = np.zeros((n, n, 3), np.float32)
    orm[:, :, 0] = 1.0
    orm[:, :, 1] = 0.42
    orm[:, :, 2] = 0.15
    return base, nrm, orm


