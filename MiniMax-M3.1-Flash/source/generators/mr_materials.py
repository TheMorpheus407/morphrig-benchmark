def _principled(mat):
    mat.use_nodes = True
    nt = mat.node_tree
    bsdf = nt.nodes.get("Principled BSDF")
    if bsdf is None:
        bsdf = nt.nodes.new("ShaderNodeBsdfPrincipled")
        nt.links.new(bsdf.outputs[0], nt.nodes["Material Output"].inputs[0])
    return nt, bsdf


def _tex_node(nt, path, name, loc, colorspace="sRGB"):
    # absolute path: a CWD relative path is re-mapped to garbage when the
    # blend file is saved somewhere else
    img = bpy.data.images.load(os.path.abspath(path), check_existing=True)
    # The normal map and the ORM map hold data, not colour.  Loading them as
    # sRGB applies the transfer curve to the vector and to the roughness, the
    # normals come out wrong and the surfaces turn into mirrors.
    try:
        img.colorspace_settings.name = colorspace
    except Exception:  # noqa: BLE001
        pass
    node = nt.nodes.new("ShaderNodeTexImage")
    node.image = img
    node.label = name
    node.name = name
    node.location = loc
    node.interpolation = 'Linear'
    return node


def _build_material(name, texdir, roughness=0.5, metallic=0.0,
                    emission=0.0, emission_color=(1.0, 0.5, 0.15),
                    normal_strength=1.0):
    mat = bpy.data.materials.new(name)
    nt, bsdf = _principled(mat)
    bsdf.inputs["Roughness"].default_value = roughness
    bsdf.inputs["Metallic"].default_value = metallic
    p = os.path.join(texdir, name)
    b = _tex_node(nt, p + "_basecolor.png", "BaseColor", (-900, 300))
    n = _tex_node(nt, p + "_normal.png", "Normal", (-900, 0), "Non-Color")
    o = _tex_node(nt, p + "_orm.png", "ORM", (-900, -300), "Non-Color")
    nt.links.new(b.outputs["Color"], bsdf.inputs["Base Color"])
    nm = nt.nodes.new("ShaderNodeNormalMap")
    nm.location = (-600, 0)
    nm.inputs["Strength"].default_value = normal_strength
    nt.links.new(n.outputs["Color"], nm.inputs["Color"])
    nt.links.new(nm.outputs["Normal"], bsdf.inputs["Normal"])
    sep = nt.nodes.new("ShaderNodeSeparateColor")
    sep.location = (-600, -300)
    nt.links.new(o.outputs["Color"], sep.inputs[0])
    nt.links.new(sep.outputs["Green"], bsdf.inputs["Roughness"])
    nt.links.new(sep.outputs["Blue"], bsdf.inputs["Metallic"])
    # ambient occlusion is stored in the ORM red channel; fold it into the
    # base colour because Blender 5's Principled BSDF has no AO input
    mult = nt.nodes.new("ShaderNodeMixRGB")
    mult.blend_type = 'MULTIPLY'
    mult.inputs[0].default_value = 1.0
    mult.location = (-380, 300)
    nt.links.new(b.outputs["Color"], mult.inputs[1])
    nt.links.new(sep.outputs["Red"], mult.inputs[2])
    nt.links.new(mult.outputs[0], bsdf.inputs["Base Color"])
    if emission > 0.0:
        bsdf.inputs["Emission Color"].default_value = (*emission_color, 1.0)
        bsdf.inputs["Emission Strength"].default_value = emission
    return mat


def _add_team_color(mat, color):
    """Give the accent material a switchable TeamColor input."""
    nt, bsdf = _principled(mat)
    rgb = nt.nodes.new("ShaderNodeRGB")
    rgb.name = "TeamColor"
    rgb.label = "TeamColor"
    rgb.location = (-900, 560)
    rgb.outputs[0].default_value = (*color, 1.0)
    tex = nt.nodes.get("BaseColor")
    mix = nt.nodes.new("ShaderNodeMixRGB")
    mix.blend_type = 'MULTIPLY'
    mix.inputs[0].default_value = 1.0
    mix.location = (-620, 560)
    nt.links.new(rgb.outputs[0], mix.inputs[2])
    nt.links.new(tex.outputs["Color"], mix.inputs[1])
    nt.links.new(mix.outputs[0], bsdf.inputs["Base Color"])
    return rgb


def build_all(texdir, layout=None):
    """Generate every texture and material.  Returns the 8 materials."""
    os.makedirs(texdir, exist_ok=True)
    made = []

    texdir = os.path.abspath(texdir)

    def emit(name, arrays):
        base, nrm, orm = arrays
        p = os.path.join(texdir, name)
        save_image(p + "_basecolor.png", np.clip(base, 0.0, 1.0))
        save_image(p + "_normal.png", np.clip(nrm, 0.0, 1.0))
        save_image(p + "_orm.png", np.clip(orm, 0.0, 1.0))
        return p

    emit("M_Skin", tex_skin())
    emit("M_Face", tex_face(layout=layout))
    emit("M_Suit", tex_suit())
    emit("M_Armor", tex_armor())
    emit("M_Metal", tex_metal())
    emit("M_Optic", tex_optic())
    emit("M_Energy", tex_energy())
    emit("M_Accent", tex_accent())

    mats = [
        # The skin and the face carry a fine pore normal map.  It is dialled
        # back a little, the pores are very high frequency and they turn to
        # noise in a close up.
        _build_material("M_Skin", texdir, roughness=0.55, metallic=0.0,
                        normal_strength=0.6),
        _build_material("M_Face", texdir, roughness=0.48, metallic=0.0,
                        normal_strength=0.5),
        _build_material("M_Suit", texdir, roughness=0.74, metallic=0.05),
        _build_material("M_Armor", texdir, roughness=0.46, metallic=0.55),
        _build_material("M_Metal", texdir, roughness=0.30, metallic=0.92),
        _build_material("M_Optic", texdir, roughness=0.38, metallic=0.10),
        _build_material("M_Energy", texdir, roughness=0.25, metallic=0.0,
                        emission=4.0, emission_color=(1.0, 0.58, 0.20)),
        _build_material("M_Accent", texdir, roughness=0.40, metallic=0.20,
                        emission=1.6, emission_color=(1.0, 0.62, 0.18)),
    ]
    _add_team_color(mats[7], (1.0, 0.62, 0.18))
    made = mats
    return made
