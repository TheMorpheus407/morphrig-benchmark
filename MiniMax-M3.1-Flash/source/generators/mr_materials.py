"""MorphRig procedural textures and materials.

Every texture in the project is generated by this script - there are no
downloaded image assets.  For each of the eight shared material slots a
base-colour / normal / ORM set is written to `source/textures` and wired
into a Blender material with the Principled BSDF.

Layout of the face atlas (`M_Face`), matching `mr_face.FACE_ATLAS`:

    u 0.00 .. 0.48, v 0.00 .. 1.00   face skin (head, lids)
    u 0.52 .. 0.74, v 0.54 .. 0.98   sclera
    u 0.76 .. 0.98, v 0.54 .. 0.98   teeth

Team accents: `M_Accent` exposes a `TeamColor` RGB node so the showcase can
switch between the amber (A) and cyan (B) variants without touching the
mesh or the rig.
"""

import math
import os

import numpy as np

import bpy

# The u range of the face skin inside the atlas, it matches
# mr_face.SKIN_U_SCALE.  The head samples the whole band, so the two ends
# of the band meet at the uv seam of the head.
SKIN_BAND_U = 0.48


# ---------------------------------------------------------------------------
# noise helpers
# ---------------------------------------------------------------------------

def _smoothstep(x):
    return x * x * (3.0 - 2.0 * x)


def value_noise(n, freq, seed):
    """Tileable value noise on an n x n grid."""
    rng = np.random.default_rng(seed)
    g = rng.random((freq, freq)).astype(np.float32)
    t = np.linspace(0.0, freq, n, endpoint=False)
    i0 = np.floor(t).astype(int)
    f = _smoothstep((t - i0)[:, None] * np.ones((1, n), np.float32))
    fx = _smoothstep((t - i0)[None, :] * np.ones((n, 1), np.float32))
    a = g[np.ix_(i0, i0)]
    b = g[np.ix_(i0, (i0 + 1) % freq)]
    c = g[np.ix_((i0 + 1) % freq, i0)]
    d = g[np.ix_((i0 + 1) % freq, (i0 + 1) % freq)]
    top = a + (b - a) * fx
    bot = c + (d - c) * fx
    return top + (bot - top) * f


def fbm(n, seed, octaves=5, base=4, gain=0.5):
    out = np.zeros((n, n), np.float32)
    amp = 1.0
    tot = 0.0
    freq = base
    for o in range(octaves):
        out += amp * value_noise(n, freq, seed + o * 977)
        tot += amp
        amp *= gain
        freq *= 2
    return out / tot


def ridge(n, seed, octaves=4, base=6):
    v = fbm(n, seed, octaves=octaves, base=base)
    return np.abs(v - 0.5) * 2.0


def normal_from_height(h, strength=2.0):
    """Normal map from a height field.

    The gradients wrap, so the map is seamless where the u of the mesh
    wraps.  np.gradient would use a one sided difference at the border and
    leave a visible line along the seam.
    """
    gy = (np.roll(h, -1, axis=0) - np.roll(h, 1, axis=0)) * 0.5
    gx = (np.roll(h, -1, axis=1) - np.roll(h, 1, axis=1)) * 0.5
    nx = -gx * strength
    ny = -gy * strength
    nz = np.ones_like(h)
    n = np.stack([nx, ny, nz], axis=-1)
    n /= np.linalg.norm(n, axis=-1, keepdims=True)
    return n * 0.5 + 0.5


def save_image(path, rgb, name=None):
    """Write an RGB float array to a PNG via a Blender image datablock."""
    h, w = rgb.shape[:2]
    rgba = np.ones((h, w, 4), np.float32)
    if rgb.shape[2] == 3:
        rgba[:, :, :3] = rgb
    else:
        rgba[:, :, :4] = rgb
    img = bpy.data.images.new(name or os.path.basename(path), width=w, height=h,
                              alpha=True, float_buffer=False)
    img.pixels.foreach_set(rgba.reshape(-1))
    img.filepath_raw = path
    img.file_format = 'PNG'
    img.save()
    bpy.data.images.remove(img)
    return path


def _tile(u, v, n):
    """Convert normalised uv to pixel coordinates."""
    return (u * n).astype(int) % n, (v * n).astype(int) % n


def paint_rect(base, rect, rgba, n, blend=1.0):
    """Paint a rectangular patch of an atlas.

    A patch with four channels carries its own alpha, the blend factor is
    then applied per pixel.  A patch with three channels is painted with a
    constant blend over the whole rectangle.
    """
    u0, v0, u1, v1 = rect
    w = max(int((u1 - u0) * n), 1)
    h = max(int((v1 - v0) * n), 1)
    uu, vv = _tile(np.linspace(u0, u1, w, endpoint=False),
                   np.linspace(v0, v1, h, endpoint=False), n)
    patch = rgba
    if patch.shape[0] != h or patch.shape[1] != w:
        ys = np.clip((np.arange(h) * patch.shape[0] // h), 0, patch.shape[0] - 1)
        xs = np.clip((np.arange(w) * patch.shape[1] // w), 0, patch.shape[1] - 1)
        patch = patch[np.ix_(ys, xs)]
    if patch.shape[2] == 4:
        col = patch[:, :, :3]
        alpha = patch[:, :, 3:4] * blend
    else:
        col = patch
        alpha = blend
    base[np.ix_(vv, uu)] = (base[np.ix_(vv, uu)] * (1.0 - alpha) +
                            col * alpha)
    return base


