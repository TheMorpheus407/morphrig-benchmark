#!/usr/bin/env python3
"""
Generates unreal/Source/MorphRig/Public/MorphRigGeneratedMeta.h from
docs/animation_manifest.json and export/animations/morph_curves.json.

Provides 1-to-1 compile-time metadata for all 96 required animation/pose entries,
exact event marker frames/names, and sampled morph curve tables.
"""

from pathlib import Path
import json

ROOT_DIR = Path(__file__).resolve().parents[2]
MANIFEST_PATH = ROOT_DIR / "docs" / "animation_manifest.json"
CURVES_PATH = ROOT_DIR / "export" / "animations" / "morph_curves.json"
OUT_HEADER = ROOT_DIR / "unreal" / "Source" / "MorphRig" / "Public" / "MorphRigGeneratedMeta.h"


def main() -> None:
    manifest = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    curves_db = json.loads(CURVES_PATH.read_text(encoding="utf-8"))
    anims = manifest["animations"]
    assert len(anims) == 96, f"Expected 96 animations, got {len(anims)}"

    marker_rows = []
    curve_tracks = []
    float_pool = []
    clip_rows = []

    for idx, entry in enumerate(anims):
        cid = entry["id"]
        form = entry["form"]
        root_pol = entry["root_movement_policy"]
        layer = entry["intended_layer"]
        frames = int(entry["frame_range"][1])
        dur = float(entry["exported_duration_seconds"])
        nom_speed = float(entry["nominal_speed_cms"])

        m_start = len(marker_rows)
        for m in entry.get("event_markers", []):
            marker_rows.append((int(m["frame"]), float(m["time_sec"]), m["name"]))
        m_count = len(marker_rows) - m_start

        c_entry = curves_db.get(cid, {})
        c_dict = c_entry.get("curves", {})
        ct_start = len(curve_tracks)
        for sk_name, vals in sorted(c_dict.items()):
            f_start = len(float_pool)
            float_pool.extend(float(v) for v in vals)
            curve_tracks.append((sk_name, f_start, len(vals)))
        ct_count = len(curve_tracks) - ct_start

        clip_rows.append(
            (
                cid,
                f"/Game/MorphRig/Animations/Anim_{cid}.Anim_{cid}",
                form,
                root_pol,
                layer,
                frames,
                dur,
                nom_speed,
                m_start,
                m_count,
                ct_start,
                ct_count,
            )
        )

    lines = [
        "// Auto-generated by source/generators/generate_ue_meta.py — DO NOT EDIT BY HAND",
        "#pragma once",
        '#include "CoreMinimal.h"',
        "",
        "struct FMorphRigMarkerMeta",
        "{",
        "\tint32 Frame;",
        "\tfloat TimeSec;",
        "\tconst TCHAR* Name;",
        "};",
        "",
        "struct FMorphRigCurveTrackMeta",
        "{",
        "\tconst TCHAR* CurveName;",
        "\tint32 SampleOffset;",
        "\tint32 SampleCount;",
        "};",
        "",
        "struct FMorphRigClipMeta",
        "{",
        "\tconst TCHAR* ClipId;",
        "\tconst TCHAR* AssetObjectPath;",
        "\tconst TCHAR* Form;",
        "\tconst TCHAR* RootPolicy;",
        "\tconst TCHAR* IntendedLayer;",
        "\tint32 Frames;",
        "\tfloat DurationSec;",
        "\tfloat NominalSpeedCms;",
        "\tint32 MarkerOffset;",
        "\tint32 MarkerCount;",
        "\tint32 CurveTrackOffset;",
        "\tint32 CurveTrackCount;",
        "};",
        "",
        f"static constexpr int32 GMorphRigClipCount = {len(clip_rows)};",
        "",
        "static const FMorphRigMarkerMeta GMorphRigMarkers[] = {",
    ]
    for fr, ts, nm in marker_rows:
        lines.append(f'\t{{ {fr}, {ts:.4f}f, TEXT("{nm}") }},')
    if not marker_rows:
        lines.append('\t{ 0, 0.0f, TEXT("") },')
    lines.append("};")
    lines.append("")

    lines.append("static const float GMorphRigCurveSamples[] = {")
    chunk = []
    for i, val in enumerate(float_pool):
        chunk.append(f"{val:.4f}f")
        if len(chunk) >= 16:
            lines.append("\t" + ", ".join(chunk) + ",")
            chunk = []
    if chunk:
        lines.append("\t" + ", ".join(chunk) + ",")
    if not float_pool:
        lines.append("\t0.0f,")
    lines.append("};")
    lines.append("")

    lines.append("static const FMorphRigCurveTrackMeta GMorphRigCurveTracks[] = {")
    for cname, f_off, f_cnt in curve_tracks:
        lines.append(f'\t{{ TEXT("{cname}"), {f_off}, {f_cnt} }},')
    if not curve_tracks:
        lines.append('\t{ TEXT(""), 0, 0 },')
    lines.append("};")
    lines.append("")

    lines.append("static const FMorphRigClipMeta GMorphRigClips[GMorphRigClipCount] = {")
    for cid, apath, form, rpol, lay, frs, dur, spd, mo, mc, co, cc in clip_rows:
        lines.append(
            f'\t{{ TEXT("{cid}"), TEXT("{apath}"), TEXT("{form}"), TEXT("{rpol}"), TEXT("{lay}"), '
            f"{frs}, {dur:.4f}f, {spd:.1f}f, {mo}, {mc}, {co}, {cc} }},"
        )
    lines.append("};")
    lines.append("")

    OUT_HEADER.parent.mkdir(parents=True, exist_ok=True)
    OUT_HEADER.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(
        f"[MetaGen] Wrote {OUT_HEADER.relative_to(ROOT_DIR)}: "
        f"{len(clip_rows)} clips, {len(marker_rows)} markers, {len(curve_tracks)} curve tracks, {len(float_pool)} float samples."
    )


if __name__ == "__main__":
    main()
